        "    else:\n"
        "        REPO_ROOT = target_clone.resolve()\n\n"
        "# Auto-install fine-tuning dependencies in cloud environments (Google Colab, Kaggle)\n"
        "if Path('/content').exists() or 'google.colab' in sys.modules or 'kaggle' in sys.modules:\n"
        "    cloud_missing = []\n"
        "    for pkg in ['trl', 'peft', 'datasets']:\n"
        "        try:\n"
        "            __import__(pkg)\n"
        "        except ImportError:\n"
        "            cloud_missing.append(pkg)\n"
        "    if cloud_missing:\n"
        "        print(f'[CLOUD SETUP] Auto-installing missing training packages: {\", \".join(cloud_missing)}...')\n"
        "        import subprocess\n"
        "        try:\n"
        "            subprocess.run([sys.executable, '-m', 'pip', 'install', '-q'] + cloud_missing, check=True)\n"
        "            print(f'[CLOUD SETUP] Successfully installed: {\", \".join(cloud_missing)}')\n"
        "        except Exception as install_err:\n"
        "            print(f'[WARNING] Auto-install failed: {install_err}. Run manually: !pip install -q trl peft datasets')\n\n"
        "# Align working directory if REPO_ROOT is a discovered subfolder\n"
        "if REPO_ROOT != Path.cwd().resolve() and (REPO_ROOT / 'contracts').exists():\n"
        "    try:\n"
        "        os.chdir(str(REPO_ROOT))\n"
        "    except Exception:\n"
        "        pass\n\n"
        "TRAINING_DIR = REPO_ROOT / 'training'\n"
        "CONTRACTS_DIR = REPO_ROOT / 'contracts'\n"
