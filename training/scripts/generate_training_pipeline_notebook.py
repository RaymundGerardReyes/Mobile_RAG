        "    except (ImportError, Exception):\n"
        "        peft.import_utils.is_torchao_available = lambda: False\n"
        "except Exception:\n"
        "    pass\n\n"
        "from transformers import AutoTokenizer, Qwen2Config, Qwen2ForCausalLM\n"
        "try:\n"
        "    from peft import LoraConfig, get_peft_model, TaskType\n"
        "except ImportError:\n"
        "    import subprocess\n"
        "    print(\"[NOTICE] 'peft' package missing. Installing via pip...\")\n"
        "    subprocess.run([sys.executable, '-m', 'pip', 'install', '-q', 'peft>=0.13.0'], check=True)\n"
        "    from peft import LoraConfig, get_peft_model, TaskType\n\n"
        "# 1. Initialize Tokenizer with ChatML template\n"
        "chat_tmpl = (\n"
        "    \"{% for message in messages %}\"\n"
        "    \"{{'<|im_start|>' + message['role'] + '\\n' + message['content'] + '<|im_end|>' + '\\n'}}\"\n"
        "    \"{% endfor %}\"\n"
        "    \"{% if add_generation_prompt %}{{ '<|im_start|>assistant\\n' }}{% endif %}\"\n"
        ")\n\n"
        "tokenizer_cache = Path.home() / '.cache/huggingface/hub/models--distilbert-base-uncased/snapshots/12040accade4e8a0f71eabdb258fecc2e7e948be'\n"
        "tokenizer = None\n\n"
        "# 1a. Try loading from pre-cached offline snapshot (fast & isolated for CI/local runs)\n"
        "if tokenizer_cache.exists():\n"
        "    try:\n"
        "        tokenizer = AutoTokenizer.from_pretrained(str(tokenizer_cache), local_files_only=True)\n"
        "        print(f'Loaded tokenizer from local cache: {tokenizer_cache.name}')\n"
        "    except Exception:\n"
        "        tokenizer = None\n\n"
        "# 1b. If running in fresh environment (e.g. Google Colab), download standard tokenizer online\n"
        "if tokenizer is None:\n"
        "    for candidate in ['bert-base-uncased', 'Qwen/Qwen2.5-0.5B-Instruct']:\n"
        "        try:\n"
        "            tokenizer = AutoTokenizer.from_pretrained(candidate, local_files_only=False)\n"
        "            print(f'Loaded tokenizer online: {candidate}')\n"
        "            break\n"
        "        except Exception:\n"
        "            continue\n\n"
        "# 1c. Graceful fallback to offline local files if running completely air-gapped\n"
        "if tokenizer is None:\n"
